--     CBS = efetiva x PartCBS / 100        IBS = efetiva x PartIBS / 100
-- PartCBS/PartIBS    = percentual de reparticao da faixa (em %). 6a faixa: IBS sai do Simples (PartIBS = 0).
-- AnoIni/AnoFim      = vigencia (ano-calendario). 2027-2028, 2029, 2030, 2031, 2032 e 2033 em diante (AnoFim 2099).
--
-- SimplesNacionalTetoISS: Anexos III e IV, 5a faixa. Quando a aliquota efetiva passa de LimiteEfetiva,
-- o ISS fica fixo em TetoISS (%) e (efetiva - TetoISS) e dividida entre CBS e IBS com PartCBS/PartIBS abaixo.
-- O teto cai a cada ano e deixa de existir em 2033 (ISS substituido pelo IBS).

